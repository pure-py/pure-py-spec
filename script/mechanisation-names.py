#!/usr/bin/env python3
"""LaTeX definitions of the mechanisation names listed by theory in the given index"""

from __future__ import annotations

import pathlib
import sys
from itertools import groupby
from operator import itemgetter


def main() -> None:
    entries = sorted(
        tuple(line.split("\t")) for line in pathlib.Path(sys.argv[1]).read_text().splitlines()
    )
    declaring = {
        name: [theory for _, theory in group] for name, group in groupby(entries, key=itemgetter(0))
    }
    print("% Generated by mechanisation-names.py")
    print(
        "\\newcommand*{\\mechref}[1]{\\ifcsname mechanisation:#1\\endcsname\\textcolor{base0B}{{\\mechnamestyle\\detokenize{#1}}}"
        "\\else\\errmessage{No mechanisation name #1}\\fi}"
    )
    # Qualify a name by theory when several theories declare it, since Isabelle qualifies names by theory
    for name, theories in declaring.items():
        for qualified in (
            [name]
            if len(theories) == 1
            else [f"{pathlib.PurePath(t).stem}.{name}" for t in theories]
        ):
            print(f"\\expandafter\\def\\csname mechanisation:{qualified}\\endcsname{{}}")


if __name__ == "__main__":
    main()
