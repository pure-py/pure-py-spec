#!/usr/bin/env python3
"""LaTeX definitions of the theorem, constant and type names defined by the session theories of the mechanisation at
the given path"""

from __future__ import annotations

import pathlib
import re
import sys

NAME = r"([A-Za-z][\w']*)"
TYPE_PARAMS = r"(?:'\w+\s+|\([^)]*\)\s+)?"
# Comments, strings and cartouches, which may contain text resembling a definition
QUOTED = re.compile(r"\(\*.*?\*\)|\"(?:[^\"\\]|\\.)*\"|\\<open>.*?\\<close>|‹[^›]*›", re.DOTALL)
CONSTANT = r"(?:definition|abbreviation|fun|function|primrec|inductive|inductive_set|coinductive|partial_function)"
DEFINITIONS = [
    re.compile(
        rf"^\s*(?:theorem|lemma|corollary|proposition|lemmas)\s+(?:\(in\s+\w+\)\s+)?{NAME}\s*(?:\[[^\]]*\]\s*)?[:=]",
        re.MULTILINE,
    ),
    re.compile(rf"^\s*{CONSTANT}(?:\s*\([^)]*\))?\s+{NAME}", re.MULTILINE),
    re.compile(rf"^\s*{CONSTANT}\b.*\band\s+{NAME}\s*::", re.MULTILINE),
    re.compile(rf"^\s*and\s+{NAME}\s*::", re.MULTILINE),
    re.compile(rf"\band\s*\n\s*{NAME}\s*::"),
    re.compile(
        rf"^\s*(?:datatype|codatatype|type_synonym|record|typedef)\s+{TYPE_PARAMS}{NAME}",
        re.MULTILINE,
    ),
    re.compile(rf"^\s*and\s+{TYPE_PARAMS}{NAME}\s*=", re.MULTILINE),
]


def theories(mechanisation: pathlib.Path) -> list[pathlib.Path]:
    paths = []
    root = (mechanisation / "ROOT").read_text()
    for session in re.split(r"^session ", root, flags=re.MULTILINE)[1:]:
        header = re.match(r'"[^"]+"(?: in "([^"]+)")?', session)
        assert header, f"session without a name in {mechanisation / 'ROOT'}"
        directory = header.group(1) or "."
        for line in session.split("theories\n", 1)[1].splitlines():
            if not re.fullmatch(r"\s+\w+", line):
                break
            paths.append(mechanisation / directory / f"{line.strip()}.thy")
    return paths


def names(theory: pathlib.Path) -> set[str]:
    text = QUOTED.sub('""', theory.read_text())
    return {name for definition in DEFINITIONS for name in definition.findall(text)}


def main() -> None:
    mechanisation = pathlib.Path(sys.argv[1])
    print("% Generated by mechanisation-names.py")
    print(
        "\\newcommand*{\\mechref}[1]{\\ifcsname mechanisation:#1\\endcsname\\texttt{\\detokenize{#1}}"
        "\\else\\errmessage{No mechanisation name #1}\\fi}"
    )
    for name in sorted(set().union(*map(names, theories(mechanisation)))):
        print(f"\\expandafter\\def\\csname mechanisation:{name}\\endcsname{{}}")


if __name__ == "__main__":
    main()
