#!/usr/bin/env python3
"""LaTeX definitions counting conformance tests by outcome, and the rules and judgements cited by tests of
ill-formed programs"""

from __future__ import annotations

import pathlib
import re
from collections import Counter

from purepy_conformance import PurePyOutcome, PythonOutcome, main_module, suite, tests

CITATION = re.compile(r"# judgement: ([a-z0-9-]+)(?:, rule: ([a-z0-9-]+))?$")


def citation(test: pathlib.Path) -> tuple[str, str | None]:
    """Judgement and optional rule cited by test"""
    m = CITATION.match(main_module(test).read_text().split("\n", 1)[0])
    assert m, f"{test} cites no judgement"
    return m.group(1), m.group(2)


def count(key: str, n: int) -> str:
    return f"\\expandafter\\def\\csname conformance:{key}\\endcsname{{{n:,}}}"


def main() -> None:
    with suite() as path:
        outcomes = Counter(test.relative_to(path).parts[:2] for test in tests(path))
        citations = [
            citation(test)
            for test in tests(path)
            if test.relative_to(path).parts[1] == PurePyOutcome.TYPING_REJECTS
        ]
    rules = {rule for _, rule in citations if rule}
    judgements = {judgement for judgement, rule in citations if not rule}
    print("% Generated by conformance-counts.py")
    print(
        "\\newcommand*{\\conformanceCount}[1]{\\ifcsname conformance:#1\\endcsname"
        "\\csname conformance:#1\\endcsname\\else\\errmessage{No conformance count #1}\\fi}"
    )
    for python in PythonOutcome:
        for purepy in PurePyOutcome:
            print(count(f"{python}/{purepy}", outcomes[python, purepy]))
        print(count(python, sum(n for (p, _), n in outcomes.items() if p == python)))
    for purepy in PurePyOutcome:
        print(count(purepy, sum(n for (_, q), n in outcomes.items() if q == purepy)))
    print(count("tests", sum(outcomes.values())))
    print(count("rules", len(rules)))
    print(count("judgements", len(judgements)))


if __name__ == "__main__":
    main()
